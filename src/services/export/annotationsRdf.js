/**
 * The annotations an OMEX archive carries: the module side-cars, and one combined Turtle file about the exported
 * model. The combined file puts the side-cars' annotations on the exported variables' ids. Its subjects are absolute
 * OMEX Metadata 1.2 IRIs (section 2.1): the model's 'http://omex-library.org/<archive>.omex/model.cellml#<id>' and
 * the entities it defines 'http://omex-library.org/<archive>.omex/annotations.ttl#<name>'. Each instance gets its
 * own copy of its side-car's entities and processes, a transporter's processes mediated by the instance's own entity.
 */

import { createGraph, termKey } from '../annotations/graph.js'
import { BQBIOL, SEMSIM, isFlowProperty, splitSubject } from '../annotations/iris.js'
import { parseRdf } from '../annotations/rdf.js'
import { SIDECAR_BASE_IRI, isProcessNode, parseSidecar, selfEntityIri } from '../annotations/sidecar.js'
import { writeTurtle } from '../annotations/turtle.js'

export { writeTurtle }

export const OMEX_METADATA_FORMAT = 'http://identifiers.org/combine.specifications/omex-metadata'
export const TURTLE_FORMAT = 'text/turtle'
export const RDF_XML_FORMAT = 'application/rdf+xml'
export const COMBINED_ANNOTATIONS_LOCATION = 'annotations.ttl'
export const SIDECAR_FOLDER = 'annotations'
/** The combined file's first line; an import skips a file starting with it, since export regenerates it. */
export const COMBINED_ANNOTATIONS_MARKER = '# Generated by PhLynx'
/** The base OMEX Metadata 1.2 gives every archive (section 2.1); its IRIs don't resolve. */
export const OMEX_LIBRARY_BASE = 'http://omex-library.org/'

/**
 * The namespace of the entities the combined file defines: 'local:' in OMEX Metadata 1.2.
 *
 * @param {string} archiveName - The archive's file name, e.g. 'model.omex'.
 * @returns {string}
 */
export function combinedLocalNamespace(archiveName) {
  return `${archiveBaseIri(archiveName)}${COMBINED_ANNOTATIONS_LOCATION}#`
}

/**
 * The absolute IRI of an archive's root, against which its files' relative IRIs resolve.
 *
 * @param {string} archiveName - The archive's file name, with or without '.omex'.
 * @returns {string} 'http://omex-library.org/<archive>.omex/'.
 */
export function archiveBaseIri(archiveName) {
  const archive = /\.omex$/i.test(archiveName) ? archiveName : `${archiveName}.omex`
  return `${OMEX_LIBRARY_BASE}${encodeURIComponent(archive)}/`
}

const named = (value) => ({ termType: 'NamedNode', value })

/**
 * Splits a mathRef into its file and component, at the last ':'.
 *
 * @param {string} mathRef - 'file:component'.
 * @returns {{ file: string, component: string }|null}
 */
function splitMathRef(mathRef) {
  const index = typeof mathRef === 'string' ? mathRef.lastIndexOf(':') : -1
  if (index <= 0 || index === mathRef.length - 1) return null
  return { file: mathRef.slice(0, index), component: mathRef.slice(index + 1) }
}

/**
 * Where a math's sidecar goes in an archive.
 *
 * @param {string} mathRef - 'file:component'.
 * @returns {string|null} 'annotations/<file>/<component>.ttl', or null for a malformed mathRef.
 */
export function sidecarLocation(mathRef) {
  const parts = splitMathRef(mathRef)
  if (!parts || [parts.file, parts.component].some((part) => part.includes('/') || part === '..')) return null
  return `${SIDECAR_FOLDER}/${parts.file}/${parts.component}.ttl`
}

/**
 * The mathRef a sidecar location in an archive is for.
 *
 * @param {string} location
 * @returns {string|null} 'file:component', or null when the location is not a sidecar's.
 */
export function mathRefFromSidecarLocation(location) {
  const match = /^annotations\/([^/]+)\/([^/]+)\.ttl$/.exec(location ?? '')
  return match && match[1] !== '..' ? `${match[1]}:${match[2]}` : null
}

/** The local-name scope of an instance's resources, 'local:<scope>-<name>'. */
const instanceScope = (instanceName) => String(instanceName).replace(/[^A-Za-z0-9_-]/g, '_')

/**
 * Builds the combined Turtle about an exported model.
 *
 * @param {Object} options
 * @param {Array} options.nodes - The exported nodes.
 * @param {Map} options.exportedIds - From generateFlattenedModel: node id -> { componentId, variableIds }.
 * @param {string} options.cellmlFileName - The model's file name in the archive.
 * @param {Map<string, { text: string, parsed?: Object, cellml?: string }>} options.sidecars - mathRef -> the
 *   sidecar text and its parse against the math (from parseSidecar), else the math to parse it against, which
 *   resolves its '#<id>' variable subjects.
 * @param {string} [options.archiveName] - The archive's file name, which names the local namespace; defaults to
 *   the model's name with '.omex'.
 * @returns {Promise<{ text: string|null, warnings: string[] }>} text is null when no node is annotated.
 */
export async function buildCombinedAnnotations({
  nodes,
  exportedIds,
  cellmlFileName,
  sidecars,
  archiveName = defaultArchiveName(cellmlFileName),
}) {
  const warnings = []
  const triples = []
  const modelNamespace = `${archiveBaseIri(archiveName)}${cellmlFileName}#`
  const modelIri = (id) => `${modelNamespace}${id}`
  const localNamespace = combinedLocalNamespace(archiveName)

  // Each sidecar's annotations, once per instance of its math, on that instance's ids.
  const parsedSidecars = new Map()
  for (const node of nodes) {
    const mathRef = node.data?.mathRef
    const sidecar = mathRef ? sidecars.get(mathRef) : null
    const ids = exportedIds.get(node.id)
    if (!sidecar?.text || !ids) continue
    if (!parsedSidecars.has(mathRef)) parsedSidecars.set(mathRef, await parseSidecarTriples(sidecar, mathRef, warnings))
    const parsed = parsedSidecars.get(mathRef)
    if (parsed) triples.push(...resubject(parsed, node.data.name, ids, { modelIri, localNamespace }, warnings))
  }

  if (!triples.length) return { text: null, warnings }
  const comments = [
    `${COMBINED_ANNOTATIONS_MARKER.replace(/^# /, '')} for this archive's model; it is written again on every export.`,
    'Subjects are the model components and variable ids.',
  ]
  const prefixes = [['model', modelNamespace], ['local', localNamespace]]
  return { text: writeTurtle(triples, prefixes, { comments }), warnings }
}

/** The archive name to assume without one: the model's, as '<name>.omex'. */
function defaultArchiveName(cellmlFileName) {
  return `${String(cellmlFileName ?? 'model').replace(/\.[^.]*$/, '')}.omex`
}

/**
 * Parses a sidecar into its triples and tells which subject is the component and which are its variables. A
 * transporter's flow processes gain the module as mediator, '[ semsim:hasPhysicalEntityReference local:entity_self ]',
 * which sidecars leave out; a process that names a mediator keeps its own.
 *
 * @returns {Promise<{ triples: Array, componentIri: string|null, variables: Map<string, string> }|null>}
 *   variables maps each variable subject to its variable's name.
 */
async function parseSidecarTriples({ text, parsed, cellml }, mathRef, warnings) {
  let triples
  try {
    triples = await parseRdf(text, { baseIri: SIDECAR_BASE_IRI })
  } catch (error) {
    warnings.push(`The sidecar for ${mathRef} doesn't parse, so it is left out of ${COMBINED_ANNOTATIONS_LOCATION}: ${error.message}`)
    return null
  }
  if (!parsed && !cellml) {
    warnings.push(`The math of ${mathRef} is missing, so its sidecar is left out of ${COMBINED_ANNOTATIONS_LOCATION}.`)
    return null
  }
  const sidecar = parsed ?? (await parseSidecar(text, { mathRef, cellml }))
  return {
    triples: [...triples, ...mediatorTriples(triples, sidecar)],
    componentIri: sidecar.component?.subject ?? null,
    variables: new Map(sidecar.variables.map(({ subject, variable }) => [subject, variable])),
  }
}

/**
 * The mediator links a transporter's flow processes lack: each process, once, mediated by 'local:entity_self'.
 *
 * @param {Array} triples - The sidecar's.
 * @param {Object} sidecar - Its parse, from parseSidecar.
 * @returns {Array}
 */
function mediatorTriples(triples, sidecar) {
  if (sidecar.component?.kind !== 'transporter' || !sidecar.componentName) return []
  const graph = createGraph(triples)
  const self = named(selfEntityIri(sidecar.componentName))
  const done = new Set()
  const added = []
  for (const { subject, property } of sidecar.variables) {
    if (!isFlowProperty(property)) continue
    for (const process of graph.objects(subject, BQBIOL.isPropertyOf)) {
      const key = termKey(process)
      if (done.has(key) || !isProcessNode(graph, process)) continue
      done.add(key)
      if (graph.objects(process, SEMSIM.hasMediatorParticipant).length) continue
      const mediator = { termType: 'BlankNode', value: `phlynx-mediator-${done.size}` }
      added.push(
        { subject: process, predicate: named(SEMSIM.hasMediatorParticipant), object: mediator },
        { subject: mediator, predicate: named(SEMSIM.hasPhysicalEntityReference), object: self }
      )
    }
  }
  return added
}

/**
 * Puts one instance's copy of a sidecar's triples on its ids. A variable subject becomes its exported id, the
 * component the instance's, and any other node of the sidecar, such as an entity, a local resource of its own,
 * 'local:<instance>-<name>' ('local:<instance>-b<n>' for a blank node).
 */
function resubject(parsed, instanceName, { componentId, variableIds }, { modelIri, localNamespace }, warnings) {
  const scope = instanceScope(instanceName)
  const local = (name) => named(`${localNamespace}${scope}-${encodeURIComponent(name)}`)
  const blankNames = new Map()
  const missing = new Set()
  const termFor = (term) => {
    if (term.termType === 'BlankNode') {
      if (!blankNames.has(term.value)) blankNames.set(term.value, `b${blankNames.size}`)
      return local(blankNames.get(term.value))
    }
    if (term.termType !== 'NamedNode' || !term.value.startsWith(SIDECAR_BASE_IRI)) return term
    if (term.value === parsed.componentIri) return named(modelIri(componentId))
    const variable = parsed.variables.get(term.value)
    if (!variable) return local(splitSubject(term.value)?.fragment || term.value)
    const id = variableIds.get(variable)
    if (id) return named(modelIri(id))
    missing.add(variable)
    return null
  }
  const out = []
  for (const triple of parsed.triples) {
    const subject = termFor(triple.subject)
    const object = termFor(triple.object)
    if (subject && object) out.push({ subject, predicate: triple.predicate, object })
  }
  if (missing.size) {
    warnings.push(`${instanceName}'s variables ${[...missing].join(', ')} have no id, so their annotations are left out.`)
  }
  return out
}

/**
 * Collects the annotation files an OMEX export writes, and the warnings to show.
 *
 * @param {Object} options
 * @param {Array} options.nodes - The exported nodes.
 * @param {Map} options.exportedIds - From generateFlattenedModel.
 * @param {string} options.cellmlFileName
 * @param {Object} options.libraryStore - Provides getModuleAnnotations(mathRef) and ensureModuleAnnotations(mathRef).
 * @param {Set<string>} [options.reservedLocations] - Locations other files take.
 * @param {string} [options.archiveName] - The archive's file name; see buildCombinedAnnotations.
 * @returns {Promise<{ files: Array<{ location: string, format: string, text: string }>, warnings: string[] }>}
 */
export async function collectAnnotationFiles({
  nodes,
  exportedIds,
  cellmlFileName,
  libraryStore,
  reservedLocations = new Set(),
  archiveName,
}) {
  const files = []
  const warnings = []
  const taken = new Set([...reservedLocations, COMBINED_ANNOTATIONS_LOCATION])

  const sidecars = new Map()
  for (const mathRef of new Set(nodes.map((node) => node.data?.mathRef).filter(Boolean))) {
    const text = libraryStore.getModuleAnnotations?.(mathRef)
    if (!text) continue
    sidecars.set(mathRef, {
      text,
      parsed: (await libraryStore.ensureModuleAnnotations?.(mathRef)) ?? undefined,
      cellml: libraryStore.availableMath?.get(mathRef),
    })
    const location = sidecarLocation(mathRef)
    if (!location || taken.has(location)) {
      warnings.push(`The sidecar for ${mathRef} has no place in the archive, so it is left out.`)
      continue
    }
    taken.add(location)
    files.push({ location, format: TURTLE_FORMAT, text })
  }

  const combined = await buildCombinedAnnotations({
    nodes,
    exportedIds,
    cellmlFileName,
    sidecars,
    ...(archiveName ? { archiveName } : {}),
  })
  warnings.push(...combined.warnings)
  if (combined.text) files.push({ location: COMBINED_ANNOTATIONS_LOCATION, format: OMEX_METADATA_FORMAT, text: combined.text })

  return { files, warnings }
}
