/**
 * The annotations an OMEX archive carries: the module sidecars, the ApiCoord instance files as loaded, and one
 * combined Turtle file about the exported model. The combined file places each bound instance under its current
 * name, copies the coordinates from the instance files, and puts the sidecars' annotations on the exported
 * variables' ids. Every subject in it is relative to the archive ('./model.cellml#name').
 */

import { APICOORD_BASE_IRI, readApiCoords } from '../annotations/apicoord.js'
import { createGraph } from '../annotations/graph.js'
import { BQBIOL, splitSubject } from '../annotations/iris.js'
import { parseRdf } from '../annotations/rdf.js'
import { SIDECAR_BASE_IRI, parseSidecar } from '../annotations/sidecar.js'
import { writeTurtle } from '../annotations/turtle.js'

export { writeTurtle }

export const OMEX_METADATA_FORMAT = 'http://identifiers.org/combine.specifications/omex-metadata'
export const TURTLE_FORMAT = 'text/turtle'
export const RDF_XML_FORMAT = 'application/rdf+xml'
export const COMBINED_ANNOTATIONS_LOCATION = 'annotations.ttl'
export const SIDECAR_FOLDER = 'annotations'
/** The combined file's first line; an import skips a file starting with it, since export regenerates it. */
export const COMBINED_ANNOTATIONS_MARKER = '# Generated by PhLynx'

const INTERNAL_BASES = [APICOORD_BASE_IRI, SIDECAR_BASE_IRI]

const named = (value) => ({ termType: 'NamedNode', value })

/**
 * Splits a mathRef into its file and component, at the last ':'.
 *
 * @param {string} mathRef - 'file:component'.
 * @returns {{ file: string, component: string }|null}
 */
function splitMathRef(mathRef) {
  const index = typeof mathRef === 'string' ? mathRef.lastIndexOf(':') : -1
  if (index <= 0 || index === mathRef.length - 1) return null
  return { file: mathRef.slice(0, index), component: mathRef.slice(index + 1) }
}

/**
 * Where a math's sidecar goes in an archive.
 *
 * @param {string} mathRef - 'file:component'.
 * @returns {string|null} 'annotations/<file>/<component>.ttl', or null for a malformed mathRef.
 */
export function sidecarLocation(mathRef) {
  const parts = splitMathRef(mathRef)
  if (!parts || [parts.file, parts.component].some((part) => part.includes('/') || part === '..')) return null
  return `${SIDECAR_FOLDER}/${parts.file}/${parts.component}.ttl`
}

/**
 * The mathRef a sidecar location in an archive is for.
 *
 * @param {string} location
 * @returns {string|null} 'file:component', or null when the location is not a sidecar's.
 */
export function mathRefFromSidecarLocation(location) {
  const match = /^annotations\/([^/]+)\/([^/]+)\.ttl$/.exec(location ?? '')
  return match && match[1] !== '..' ? `${match[1]}:${match[2]}` : null
}

/**
 * The manifest format for an instance file.
 *
 * @param {string} format - The stored format, e.g. 'turtle' or 'rdfxml'.
 * @returns {string}
 */
export function instanceFileFormat(format) {
  return /xml|rdf$/i.test(format ?? '') ? RDF_XML_FORMAT : TURTLE_FORMAT
}

/**
 * Writes an internal IRI as the relative one its file had, e.g. './apicoords.rdf#coord_x'.
 *
 * @param {string} iri
 * @returns {string}
 */
function relativise(iri) {
  const base = INTERNAL_BASES.find((prefix) => iri.startsWith(prefix))
  return base ? `./${iri.slice(base.length)}` : iri
}

/**
 * The bound instances an export should warn about: renamed since their instance file was loaded, or named in
 * another model file. The original instance file then points at the wrong components; the combined file doesn't.
 *
 * @param {Array} nodes - The exported nodes.
 * @param {string} cellmlFileName - The model's file name in the archive.
 * @returns {Array<{ name: string, fileName: string, file: string|null }>} name is the current name, fileName the
 *   instance file's, and file the model file the instance file names.
 */
export function staleInstanceNames(nodes, cellmlFileName) {
  const stale = []
  for (const node of nodes) {
    const apiCoord = node.data?.apiCoord
    if (!apiCoord?.coordIri || !apiCoord.subject) continue
    const parts = splitSubject(apiCoord.subject)
    const fileName = apiCoord.name ?? parts?.fragment ?? null
    const file = parts?.file ?? null
    if (fileName !== node.data.name || (file && file !== cellmlFileName)) {
      stale.push({ name: node.data.name, fileName, file })
    }
  }
  return stale
}

/**
 * Builds the combined Turtle about an exported model.
 *
 * @param {Object} options
 * @param {Array} options.nodes - The exported nodes.
 * @param {Map} options.exportedIds - From generateFlattenedModel: node id -> { componentId, variableIds }.
 * @param {string} options.cellmlFileName - The model's file name in the archive.
 * @param {Map<string, { text: string, parsed?: Object }>} options.sidecars - mathRef -> the sidecar text and its
 *   parse against the math (from parseSidecar), which resolves '#id' subjects; parsed without the math if absent.
 * @param {Array<{ location: string, format: string, text: string }>} options.instanceSources - The instance files.
 * @returns {Promise<{ text: string|null, warnings: string[] }>} text is null when no node is annotated.
 */
export async function buildCombinedAnnotations({ nodes, exportedIds, cellmlFileName, sidecars, instanceSources = [] }) {
  const warnings = []
  const triples = []
  const modelIri = (id) => `./${cellmlFileName}#${id}`

  const bound = nodes.filter((node) => node.data?.apiCoord?.coordIri)
  for (const node of bound) {
    triples.push({
      subject: named(modelIri(exportedIds.get(node.id)?.componentId ?? node.data.name)),
      predicate: named(BQBIOL.is),
      object: named(relativise(node.data.apiCoord.coordIri)),
    })
  }

  // The coordinates, as each instance file has them, without its lines placing instances under their old names.
  for (const [index, source] of instanceSources.entries()) {
    let fileTriples
    try {
      fileTriples = await parseRdf(source.text, { format: source.format, baseIri: APICOORD_BASE_IRI })
    } catch (error) {
      warnings.push(`The instance file ${source.location} doesn't parse, so its coordinates are left out: ${error.message}`)
      continue
    }
    const placed = new Set(readApiCoords(createGraph(fileTriples)).instances.map(({ subject }) => subject))
    // Instance names hold no hyphen, so these labels can't meet an instance's.
    const blank = blankNodeNamer(`file-${index}`)
    for (const triple of fileTriples) {
      if (triple.subject.termType === 'NamedNode' && placed.has(triple.subject.value)) continue
      triples.push({ subject: copyTerm(triple.subject, blank), predicate: triple.predicate, object: copyTerm(triple.object, blank) })
    }
  }

  // Each sidecar's annotations, once per instance of its math, on that instance's ids.
  const parsedSidecars = new Map()
  for (const node of nodes) {
    const mathRef = node.data?.mathRef
    const sidecar = mathRef ? sidecars.get(mathRef) : null
    const ids = exportedIds.get(node.id)
    if (!sidecar?.text || !ids) continue
    if (!parsedSidecars.has(mathRef)) parsedSidecars.set(mathRef, await parseSidecarTriples(sidecar, mathRef, warnings))
    const parsed = parsedSidecars.get(mathRef)
    if (parsed) triples.push(...resubject(parsed, node.data.name, ids, modelIri, warnings))
  }

  if (!triples.length) return { text: null, warnings }
  const comments = [
    `${COMBINED_ANNOTATIONS_MARKER.replace(/^# /, '')} for this archive's model; it is written again on every export.`,
    'Subjects are the model components and variable ids; the instance files hold the coordinates as loaded.',
  ]
  return { text: writeTurtle(triples, [['model', `./${cellmlFileName}#`]], { comments }), warnings }
}

/**
 * Parses a sidecar into its triples and tells which subject is the component and which are its variables.
 *
 * @returns {Promise<{ triples: Array, componentIri: string|null, variables: Map<string, string> }|null>}
 *   variables maps each variable subject to its variable's name.
 */
async function parseSidecarTriples({ text, parsed }, mathRef, warnings) {
  let triples
  try {
    triples = await parseRdf(text, { baseIri: SIDECAR_BASE_IRI })
  } catch (error) {
    warnings.push(`The sidecar for ${mathRef} doesn't parse, so it is left out of ${COMBINED_ANNOTATIONS_LOCATION}: ${error.message}`)
    return null
  }
  const sidecar = parsed ?? (await parseSidecar(text, { mathRef }))
  return {
    triples,
    componentIri: sidecar.component?.subject ?? null,
    variables: new Map(sidecar.variables.map(({ subject, variable }) => [subject, variable])),
  }
}

/**
 * Puts one instance's copy of a sidecar's triples on its ids. A variable subject becomes its exported id, the
 * component the instance's, and any other node of the sidecar a blank node of its own.
 */
function resubject(parsed, instanceName, { componentId, variableIds }, modelIri, warnings) {
  const blank = blankNodeNamer(instanceName)
  const missing = new Set()
  const termFor = (term) => {
    if (term.termType === 'BlankNode') return blank(term.value)
    if (term.termType !== 'NamedNode' || !term.value.startsWith(SIDECAR_BASE_IRI)) return term
    if (term.value === parsed.componentIri) return named(modelIri(componentId))
    const variable = parsed.variables.get(term.value)
    if (!variable) return blank(`iri:${term.value}`)
    const id = variableIds.get(variable)
    if (id) return named(modelIri(id))
    missing.add(variable)
    return null
  }
  const out = []
  for (const triple of parsed.triples) {
    const subject = termFor(triple.subject)
    const object = termFor(triple.object)
    if (subject && object) out.push({ subject, predicate: triple.predicate, object })
  }
  if (missing.size) {
    warnings.push(`${instanceName}'s variables ${[...missing].join(', ')} have no id, so their annotations are left out.`)
  }
  return out
}

/** Names blank nodes uniquely within one copy: '<scope>-b<n>'. */
function blankNodeNamer(scope) {
  const labels = new Map()
  const safeScope = String(scope).replace(/[^A-Za-z0-9_-]/g, '_')
  return (label) => {
    if (!labels.has(label)) labels.set(label, { termType: 'BlankNode', value: `${safeScope}-b${labels.size}` })
    return labels.get(label)
  }
}

function copyTerm(term, blank) {
  if (term.termType === 'BlankNode') return blank(term.value)
  if (term.termType === 'NamedNode') return named(relativise(term.value))
  return term
}

/**
 * Collects the annotation files an OMEX export writes, and the warnings to show.
 *
 * @param {Object} options
 * @param {Array} options.nodes - The exported nodes.
 * @param {Map} options.exportedIds - From generateFlattenedModel.
 * @param {string} options.cellmlFileName
 * @param {Object} options.libraryStore - Provides getModuleAnnotations(mathRef) and ensureModuleAnnotations(mathRef).
 * @param {Array<{ location: string, format: string, text: string }>} options.instanceSources
 * @param {Set<string>} [options.reservedLocations] - Locations other files take.
 * @returns {Promise<{ files: Array<{ location: string, format: string, text: string }>, warnings: string[] }>}
 */
export async function collectAnnotationFiles({
  nodes,
  exportedIds,
  cellmlFileName,
  libraryStore,
  instanceSources = [],
  reservedLocations = new Set(),
}) {
  const files = []
  const warnings = []
  const taken = new Set([...reservedLocations, COMBINED_ANNOTATIONS_LOCATION])

  const sidecars = new Map()
  for (const mathRef of new Set(nodes.map((node) => node.data?.mathRef).filter(Boolean))) {
    const text = libraryStore.getModuleAnnotations?.(mathRef)
    if (!text) continue
    sidecars.set(mathRef, { text, parsed: (await libraryStore.ensureModuleAnnotations?.(mathRef)) ?? undefined })
    const location = sidecarLocation(mathRef)
    if (!location || taken.has(location)) {
      warnings.push(`The sidecar for ${mathRef} has no place in the archive, so it is left out.`)
      continue
    }
    taken.add(location)
    files.push({ location, format: TURTLE_FORMAT, text })
  }

  const hasBound = nodes.some((node) => node.data?.apiCoord?.coordIri)
  const sources = hasBound ? instanceSources : []
  for (const source of sources) {
    const location = source.location.replace(/^(\.\/)+|^\/+/, '')
    if (!location || location.split('/').includes('..') || taken.has(location)) {
      warnings.push(`The instance file ${source.location} would overwrite another file, so it is left out.`)
      continue
    }
    taken.add(location)
    files.push({ location, format: instanceFileFormat(source.format), text: source.text })
  }

  const combined = await buildCombinedAnnotations({ nodes, exportedIds, cellmlFileName, sidecars, instanceSources: sources })
  warnings.push(...combined.warnings)
  if (combined.text) files.push({ location: COMBINED_ANNOTATIONS_LOCATION, format: OMEX_METADATA_FORMAT, text: combined.text })

  const stale = staleInstanceNames(nodes, cellmlFileName)
  if (stale.length) {
    const listed = stale
      .map(({ name, fileName, file }) =>
        file && file !== cellmlFileName ? `${fileName} (now ${name}, in ${file})` : `${fileName} (now ${name})`
      )
      .join(', ')
    warnings.push(
      `Renamed since the instance file was loaded: ${listed}. The instance file is kept as loaded, so it names ` +
        `the old components; ${COMBINED_ANNOTATIONS_LOCATION} has the current names.`
    )
  }
  return { files, warnings }
}
